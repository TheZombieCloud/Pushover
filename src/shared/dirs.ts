/** Nearest direction index for a vector (no trig: best dot product). */
export const dirFor = (dx: number, dy: number): number => {
  let best = 0;
  let bestDot = -Infinity;
  for (let i = 0; i < DIRS; i++) {
    const [ux, uy] = DIR[i]!;
    const dot = dx * ux + dy * uy;
    if (dot > bestDot) {
      bestDot = dot;
      best = i;
    }
  }
  return best;
};
